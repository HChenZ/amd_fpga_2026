#!/usr/bin/env python3
"""Hold-oriented floorplans: separate the register pair that owns WHS.

Evidence (champion netlist `pl_ndh_crit200_ntr`, build/reports/.../hold_paths.rpt):

    +0.017  0.381 ns  1 level   u_ascon_mmio/u_ascon_core/u_crypto_aead/p12_inst/s_out_reg[315]
                             -> u_ascon_mmio/u_ascon_core/u_crypto_aead/s4_reg[59]
    +0.020  0.300 ns  0 level   run_key_reg[27] -> key_r_reg[27]
    ...

WHS is thin because those registers sit a LUT (or a wire) apart.  Hold margin can only
be bought by making the *minimum* delay longer, i.e. by physically pulling the pair
apart.  `s_out_reg` lives inside `u_crypto_aead/p12_inst` while `s4_reg` lives one
level up, so a pblock boundary between `p12_inst` and the rest of `u_ascon_mmio`
separates them.

Collateral measured on the accepted netlist (setup paths < 2.0 ns that cross the
boundary): only `crypto_aead -> p12_inst` 106 paths, worst **+0.810 ns**; and
`p12_inst -> crypto_aead` has *no* setup path under 2.0 ns.  So the split spends
slack-rich wire, not critical wire.

Geometry (u_ascon_mmio = 18133 cells / 5842 LUT / 11201 FF; p12_inst = 1628 / 979 / 646):

    hfp1 (far)   p12_inst  X26..49 / Y0..49     (1200 slice)
                 ascon_mmio X79..113 / Y50..149 (3500)
                 rest       X0..25 + X50..113 / Y0..49, X26..78 / Y50..149
    hfp2 (near)  p12_inst  X26..49 / Y0..49
                 ascon_mmio X50..113 / Y0..49  (3200)
                 rest       X0..25 / Y0..49, X26..113 / Y50..149

    python build/backend_opt_20261021/floorplan_hold.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "build/local/backend_opt_20261021/floorplan"

HEAD = """# GENERATED by build/backend_opt_20261021/floorplan_hold.py -- {name}
# separates u_crypto_aead/p12_inst from the rest of u_ascon_mmio so the hold-critical
# 1-LUT register pairs (s_out -> s4, p12_in -> s_reg, ...) get a longer minimum delay.
proc bopt_pb {{name cells args}} {{
    if {{[llength [get_pblocks -quiet $name]] > 0}} {{ delete_pblocks $name }}
    create_pblock $name
    if {{[llength $cells] == 0}} {{ error "empty cell list for $name" }}
    add_cells_to_pblock $name $cells
    foreach r $args {{ resize_pblock $name -add $r }}
    puts "PB $name ranges=$args cells=[llength $cells]"
}}

set bopt_p12  [get_cells -quiet u_soc_axi_top/u_soc_top/u_ascon_mmio/u_ascon_core/u_crypto_aead/p12_inst]
set bopt_mmio [get_cells -hier -quiet -filter {{IS_PRIMITIVE && NAME =~ "*u_ascon_mmio/*" && NAME !~ "*u_crypto_aead/p12_inst/*" && PRIMITIVE_GROUP != "IO" && PRIMITIVE_GROUP != "CLK" && PRIMITIVE_GROUP != "BLOCKRAM" && PRIMITIVE_GROUP != "DSP"}}]
set bopt_rest [get_cells -hier -quiet -filter {{IS_PRIMITIVE && NAME !~ "*u_ascon_mmio*" && PRIMITIVE_GROUP != "IO" && PRIMITIVE_GROUP != "CLK" && PRIMITIVE_GROUP != "BLOCKRAM" && PRIMITIVE_GROUP != "DSP"}}]
"""

PLANS = {
    "hfp1": [
        ("pb_hf_p12", "bopt_p12", ["SLICE_X26Y0:SLICE_X49Y49"]),
        ("pb_hf_mmio", "bopt_mmio", ["SLICE_X79Y50:SLICE_X113Y149"]),
        ("pb_hf_rest", "bopt_rest", ["SLICE_X0Y0:SLICE_X25Y49",
                                     "SLICE_X50Y0:SLICE_X113Y49",
                                     "SLICE_X26Y50:SLICE_X78Y149"]),
    ],
    "hfp2": [
        ("pb_hf_p12", "bopt_p12", ["SLICE_X26Y0:SLICE_X49Y49"]),
        ("pb_hf_mmio", "bopt_mmio", ["SLICE_X50Y0:SLICE_X113Y49"]),
        ("pb_hf_rest", "bopt_rest", ["SLICE_X0Y0:SLICE_X25Y49",
                                     "SLICE_X26Y50:SLICE_X113Y149"]),
    ],
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, blocks in PLANS.items():
        lines = [HEAD.format(name=name)]
        for pb, cells, ranges in blocks:
            rl = " ".join("{" + r + "}" for r in ranges)
            lines.append(f"bopt_pb {pb} ${cells} {rl}")
        text = "\n".join(lines) + "\n"
        path = OUT / f"{name}.tcl"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

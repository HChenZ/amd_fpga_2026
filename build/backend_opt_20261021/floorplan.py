#!/usr/bin/env python3
"""Emit dependency-driven pblock scripts for the placement campaign.

Evidence used (see dep_analysis.py output on the accepted +0.007 routed netlist):

    dcache -> ascon_mmio        8858 paths, worst +0.525   (slack-rich, wide MMIO bus)
    ascon_mmio -> ascon_mmio    2068 paths, worst +0.108   (own wall)
    if_stage -> ascon_ise        647 paths, worst +0.145   (ISE sits in EX, must stay)
    id_ex -> dcache              401 paths, worst +0.007   (the WNS family)
    id_ex -> id_ex               307 paths, worst +0.034
    id_ex -> if_id               165 paths, worst +0.178
    icache -> id_ex              107 paths, worst +0.197

So the CPU pipeline cluster (if_stage, icache, if_id, id_ex, ex_stage/ISE, csr,
dcache, ex_mem, mem_wb) must stay inside one compact region, while u_ascon_mmio
-- 18k cells / 11.2k FF, connected to the CPU only through slack-rich bus nets --
gets its own region and stops competing for area inside the pipeline.

Current placement of the reference netlist, for comparison:
    u_cpu_core   X32..106  Y0..113   (10461 cells)
    u_dcache     X35..106  Y3..113   (stretched over 110 rows)
    u_ascon_mmio X27..99   Y26..120  (18114 cells, interleaved with the CPU)

Device: X0..113, Y0..149, clock regions
    X0Y0 X0-49 Y0-49 (2500 slices, 1000 SLICEM)   X1Y0 X50-113 Y0-49 (3200, 850)
    X0Y1 X26-49 Y50-99 (1200, 400)                X1Y1 X50-113 Y50-99 (2600, 850)
    X0Y2 X26-49 Y100-149 (1200, 400)              X1Y2 X50-113 Y100-149 (2600, 850)

    python build/backend_opt_20261021/floorplan.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "build/local/backend_opt_20261021/floorplan"

HEAD = """# GENERATED by build/backend_opt_20261021/floorplan.py -- floorplan {name}
# source netlist: post-synth top_pl_bram.dcp of HEAD; see docs/backend_placement_campaign.md
proc bopt_pb {{name cells range density}} {{
    if {{[llength [get_pblocks -quiet $name]] > 0}} {{ delete_pblocks $name }}
    create_pblock $name
    if {{[llength $cells] == 0}} {{ error "empty cell list for $name" }}
    add_cells_to_pblock $name $cells
    resize_pblock $name -add $range
    # PLACE_DENSITY is not a pblock property in 2025.2 (Netlist 29-177); kept as a
    # guarded no-op so the density knob can never kill an arm.
    if {{$density ne ""}} {{ catch {{ set_property PLACE_DENSITY $density [get_pblocks $name] }} dw }}
    puts "PB $name range=$range cells=[llength $cells] density=$density"
}}

set bopt_dens ""
if {{[info exists ::env(BOPT_DENSITY)]}} {{ set bopt_dens $::env(BOPT_DENSITY) }}

set bopt_cpu    [get_cells -quiet u_soc_axi_top/u_soc_top/u_cpu_core]
set bopt_crypto [get_cells -quiet u_soc_axi_top/u_soc_top/u_ascon_mmio]
# System periphery: logic only. IO/clock/BRAM/DSP cells are left unconstrained so a
# region that happens to contain no site of that type can never fail placement.
set bopt_rest   [get_cells -hier -quiet -filter {{IS_PRIMITIVE && PRIMITIVE_GROUP != "IO" && PRIMITIVE_GROUP != "CLK" && PRIMITIVE_GROUP != "BLOCKRAM" && PRIMITIVE_GROUP != "DSP" && NAME !~ "*u_cpu_core*" && NAME !~ "*u_ascon_mmio*" && REF_NAME != "GND" && REF_NAME != "VCC"}}]
"""

PLANS = {
    # CPU keeps the whole bottom row of clock regions (X0Y0 + X1Y0 = 5700 slices),
    # everything else shares the two upper rows. Coarsest split, lowest risk.
    "fp2": [
        ("pb_cpu", "bopt_cpu", "SLICE_X0Y0:SLICE_X113Y49"),
        ("pb_rest", "bopt_rest", "SLICE_X26Y50:SLICE_X113Y149"),
    ],
    # Same CPU band, but the slack-rich system periphery (bus, uart, gpio, clint,
    # cpi, axi) sits in the left upper column between the CPU band and crypto,
    # and u_ascon_mmio (18k cells, own wall at +0.108) gets the right upper block.
    "fp3": [
        ("pb_cpu", "bopt_cpu", "SLICE_X0Y0:SLICE_X113Y49"),
        ("pb_crypto", "bopt_crypto", "SLICE_X50Y50:SLICE_X113Y149"),
        ("pb_sys", "bopt_rest", "SLICE_X26Y50:SLICE_X49Y149"),
    ],
    # Column split instead of band split: the CPU pipeline owns the left clock
    # region column, everything else the right one. Same dependency grouping,
    # opposite geometry -- tells whether the band split's win (if any) is real.
    "fpc": [
        ("pb_cpu", "bopt_cpu", "SLICE_X0Y0:SLICE_X49Y149"),
        ("pb_rest", "bopt_rest", "SLICE_X50Y0:SLICE_X113Y149"),
    ],
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, blocks in PLANS.items():
        lines = [HEAD.format(name=name)]
        for pb, cells, rng in blocks:
            lines.append(f'bopt_pb {pb} ${cells} {{{rng}}} $bopt_dens')
        text = "\n".join(lines) + "\n"
        path = OUT / f"{name}.tcl"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}  blocks={[b[0] for b in blocks]}")


if __name__ == "__main__":
    main()
